<#
.SYNOPSIS
    Generates (or checks) the lock-probe CFCs under models\lockprobe\.

.DESCRIPTION
    The original benchmark shapes construct the SAME class on every iteration, which is the
    worst case for a per-class construction lock and cannot show where such a lock helps or
    where its "hold every ancestor's lock too" rule collapses back to a global lock. These
    families give /benchmark/construct the shapes it needs:

        Leaf01..LeafNN            no extends                    shape=fanout
        SibBase, Sib01..SibNN     all extend SibBase            shape=siblings
        Deep1..Deep5              five-level extends chain      shape=deep
        SlowLeaf01..SlowLeafNN    sleep in the pseudo-constructor, no extends      shape=slowfanout
        SlowSib01..SlowSibNN      sleep in the pseudo-constructor, extend SibBase  shape=slowsiblings
        SlowInit                  sleep in init(), not the pseudo-constructor      shape=slowinit

    The files are generated once and committed. Generating them at request time would put
    compilation on the very path being measured, and would churn the Dropbox-synced tree.

.PARAMETER Width
    How many leaf classes per family (default 16, the maximum /benchmark/construct accepts).

.PARAMETER Check
    Regenerate in memory and compare with what is on disk. Exit code 1 on drift.

.EXAMPLE
    .\scripts\New-LockProbeModels.ps1
.EXAMPLE
    .\scripts\New-LockProbeModels.ps1 -Check
#>
[CmdletBinding()]
param(
    [int]    $Width = 16,
    [switch] $Check
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$outDir   = Join-Path $repoRoot 'models\lockprobe'

$header = @"
/**
 * GENERATED by scripts/New-LockProbeModels.ps1 - do not edit by hand.
 * {0}
 */
"@

# Every probe keeps the same contract Benchmark.cfc checks: setValue/getValue for the
# checksum and getIdentity for the "did I get the class I asked for" cross-check.
function Get-LeafBody {
    param( [int] $Index, [string] $Extends, [bool] $SleepInCtor, [bool] $SleepInInit, [bool] $SuperInit )
    $ext   = if ( $Extends ) { " extends=""$Extends""" } else { '' }
    $sleep = "`tsleep( request.keyExists( ""lockProbeSleepMs"" ) ? request.lockProbeSleepMs : 3 );`n"
    $b = New-Object System.Text.StringBuilder
    [void]$b.Append( "component$ext {`n`n" )
    [void]$b.Append( "`tvariables.value    = 0;`n" )
    [void]$b.Append( "`tvariables.identity = $Index;`n" )
    [void]$b.Append( "`tvariables.propA    = ""alpha"";`n" )
    [void]$b.Append( "`tvariables.propB    = [];`n" )
    if ( $SleepInCtor ) { [void]$b.Append( "`t// The sleep runs inside the engine's construction lock window.`n" ); [void]$b.Append( $sleep ) }
    [void]$b.Append( "`n`tfunction init() {`n" )
    if ( $SuperInit ) { [void]$b.Append( "`t`tsuper.init();`n" ) }
    if ( $SleepInInit ) { [void]$b.Append( "`t`t// init() is invoked by the caller after construction returns, i.e. outside the lock.`n" ); [void]$b.Append( "`t" + $sleep ) }
    [void]$b.Append( "`t`tvariables.propB = [ 1, 2, 3 ];`n`t`treturn this;`n`t}`n`n" )
    [void]$b.Append( "`tfunction setValue( required numeric value ) {`n`t`tvariables.value = arguments.value;`n`t`treturn this;`n`t}`n`n" )
    [void]$b.Append( "`tnumeric function getValue() {`n`t`treturn variables.value;`n`t}`n`n" )
    [void]$b.Append( "`tnumeric function getIdentity() {`n`t`treturn variables.identity;`n`t}`n`n" )
    [void]$b.Append( "`tfunction getPropA() {`n`t`treturn variables.propA;`n`t}`n`n" )
    [void]$b.Append( "`tfunction getPropB() {`n`t`treturn variables.propB;`n`t}`n`n}`n" )
    return $b.ToString()
}

function Get-BaseBody {
    param( [string] $Extends, [string] $Prefix, [string] $Note )
    $ext = if ( $Extends ) { " extends=""$Extends""" } else { '' }
    $sup = if ( $Extends ) { "`t`tsuper.init();`n" } else { '' }
    return @"
component$ext {

	variables.${Prefix}A = "$Prefix-a";
	variables.${Prefix}B = 0;

	function init() {
$sup		variables.${Prefix}B = 1;
		return this;
	}

	function get$( $Prefix.Substring(0,1).ToUpper() + $Prefix.Substring(1) )A() {
		return variables.${Prefix}A;
	}

	function touch$( $Prefix.Substring(0,1).ToUpper() + $Prefix.Substring(1) )() {
		variables.${Prefix}B = variables.${Prefix}B + 1;
		return this;
	}

}
"@
}

$files = [ordered]@{}
foreach ( $i in 1..$Width ) {
    $nn = '{0:D2}' -f $i
    $files[ "Leaf$nn.cfc" ]     = ( $header -f "fanout: leaf $i of $Width, no extends. One construction lock." ) + "`n" + ( Get-LeafBody -Index $i -Extends '' -SleepInCtor $false -SleepInInit $false -SuperInit $false )
    $files[ "Sib$nn.cfc" ]      = ( $header -f "siblings: leaf $i of $Width, extends SibBase. Own lock plus the shared SibBase lock." ) + "`n" + ( Get-LeafBody -Index $i -Extends 'models.lockprobe.SibBase' -SleepInCtor $false -SleepInInit $false -SuperInit $true )
    $files[ "SlowLeaf$nn.cfc" ] = ( $header -f "slowfanout: leaf $i of $Width, no extends, sleeps in the pseudo-constructor." ) + "`n" + ( Get-LeafBody -Index $i -Extends '' -SleepInCtor $true -SleepInInit $false -SuperInit $false )
    $files[ "SlowSib$nn.cfc" ]  = ( $header -f "slowsiblings: leaf $i of $Width, extends SibBase, sleeps in the pseudo-constructor while holding the SibBase lock." ) + "`n" + ( Get-LeafBody -Index $i -Extends 'models.lockprobe.SibBase' -SleepInCtor $true -SleepInInit $false -SuperInit $true )
}
$files[ 'SibBase.cfc' ]  = ( $header -f 'siblings/slowsiblings: the one base every Sib and SlowSib leaf extends.' ) + "`n" + ( Get-BaseBody -Extends '' -Prefix 'base' -Note '' )
$files[ 'SlowInit.cfc' ] = ( $header -f 'slowinit: sleeps in init(), which the caller invokes after construction returns.' ) + "`n" + ( Get-LeafBody -Index 1 -Extends '' -SleepInCtor $false -SleepInInit $true -SuperInit $false )
$files[ 'Deep1.cfc' ]    = ( $header -f 'deep: level 1 (root) of a five-level extends chain.' ) + "`n" + ( Get-BaseBody -Extends '' -Prefix 'deep1' )
foreach ( $lvl in 2..4 ) {
    $files[ "Deep$lvl.cfc" ] = ( $header -f "deep: level $lvl of a five-level extends chain." ) + "`n" + ( Get-BaseBody -Extends "models.lockprobe.Deep$( $lvl - 1 )" -Prefix "deep$lvl" )
}
$files[ 'Deep5.cfc' ] = ( $header -f 'deep: level 5 (the leaf) of a five-level extends chain. Five locks per construction.' ) + "`n" + ( Get-LeafBody -Index 5 -Extends 'models.lockprobe.Deep4' -SleepInCtor $false -SleepInInit $false -SuperInit $true )

if ( $Check ) {
    $drift = @()
    foreach ( $name in $files.Keys ) {
        $path = Join-Path $outDir $name
        if ( -not ( Test-Path $path ) ) { $drift += "$name missing"; continue }
        $onDisk = [System.IO.File]::ReadAllText( $path ) -replace "`r`n", "`n"
        if ( $onDisk -ne $files[ $name ] ) { $drift += "$name differs" }
    }
    $extra = Get-ChildItem $outDir -Filter '*.cfc' -ErrorAction SilentlyContinue | Where-Object { -not $files.Contains( $_.Name ) } | ForEach-Object { "$($_.Name) not generated" }
    $drift += $extra
    if ( $drift.Count ) { $drift | ForEach-Object { Write-Host $_ -ForegroundColor Red }; exit 1 }
    Write-Host "models\lockprobe matches the generator ($( $files.Count ) files)." -ForegroundColor Green
    exit 0
}

if ( -not ( Test-Path $outDir ) ) { New-Item -ItemType Directory -Path $outDir | Out-Null }
foreach ( $name in $files.Keys ) {
    [System.IO.File]::WriteAllText( ( Join-Path $outDir $name ), $files[ $name ], ( New-Object System.Text.UTF8Encoding $false ) )
}
Write-Host "Wrote $( $files.Count ) files to $outDir" -ForegroundColor Green
