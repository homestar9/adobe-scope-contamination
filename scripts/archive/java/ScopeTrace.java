    /**
     * Record that this scope was created while serving the current request. Scopes created
     * outside a request (framework singletons built at startup) are not tracked: they are shared
     * on purpose, so sharing them proves nothing.
     */
    private static void rememberOwner( Object scope, String cfc ) { rememberOwner( scope, cfc, null ); }

    /**
     * @param holder the component this scope was created for, when there is one. Recording it is
     *               what lets a later crossing say WHICH of two very different things happened:
     *               the same component being used by two requests, or one scope object being
     *               shared by two different components.
     */
    private static void rememberOwner( Object scope, String cfc, Object holder ) {
        if ( scope == null ) return;
        Long reqId = CURRENT_REQ_ID.get();
        if ( reqId == null ) return;
        if ( SCOPE_OWNER.size() >= MAX_TRACKED_SCOPES ) { count( "ownerTable.full" ); return; }

        Integer key = Integer.valueOf( System.identityHashCode( scope ) );
        // Labels this class writes itself carry a ':' marker and are already precise — leaf()
        // would eat the part after "cfc" and make "invokeStruct:BaseEntity.cfc#init" unreadable.
        String who = ( cfc == null ) ? "-" : ( cfc.indexOf( ':' ) >= 0 ? cfc : leaf( cfc ) );
        String label = nz( CURRENT_REQ.get() ) + "/" + who;
        Integer holderId = ( holder == null ) ? null : Integer.valueOf( System.identityHashCode( holder ) );
        Object[] existing = SCOPE_OWNER.putIfAbsent( key, new Object[]{ scope, reqId, label, holderId } );
        if ( existing == null ) {
            OWNED.get().addLast( key );
            return;
        }

        // An honesty check on the whole detector. If ColdFusion ever recycles a scope object,
        // a second request could legitimately be handed the same object after the first is done
        // with it, and this table would then report a crossing that never happened. Any count
        // here means the crossing numbers need re-reading; zero means they can be trusted.
        if ( existing[0] == scope && !reqId.equals( existing[1] ) ) {
            count( "ownerTable.scopeReusedByAnotherRequest" );
        }
    }

    /**
     * Returns the owner entry when this scope belongs to a DIFFERENT in-flight request, or null
     * when it is this request's own scope, an untracked scope, or a stale identity number.
     *
     * The reference check is the important part. Two objects can share an identityHashCode, so
     * without comparing the stored object with == this would report crossings that never
     * happened.
     */
    private static Object[] foreignOwner( Object scope ) {
        if ( scope == null ) return null;
        Long reqId = CURRENT_REQ_ID.get();
        if ( reqId == null ) return null;
        Object[] entry = SCOPE_OWNER.get( Integer.valueOf( System.identityHashCode( scope ) ) );
        if ( entry == null ) return null;
        if ( entry[0] != scope ) { count( "ownerTable.identityCollision" ); return null; }
        if ( reqId.equals( entry[1] ) ) return null;
        return entry;
    }

    /**
     * Roll this request's tallies into the totals for its outcome, then drop its scopes so the
     * owner table only ever holds requests that are still running.
     */
    private static void endRequest( String outcome ) {
        if ( outcome != null && CURRENT_REQ_ID.get() != null ) {
            long[] s = STATS.get();
            count( "requests." + outcome );
            for ( int i = 0; i < S_COUNT; i++ ) {
                if ( s[i] != 0L ) add( "perRequest." + outcome + "." + STAT_NAMES[i], s[i] );
            }
        }
        Long id = CURRENT_REQ_ID.get();
        if ( id != null ) LIVE_REQS.remove( id );
        ArrayDeque<Integer> mine = OWNED.get();
        for ( Integer k = mine.pollFirst(); k != null; k = mine.pollFirst() ) {
            SCOPE_OWNER.remove( k );
        }
        CURRENT_REQ.remove();
        CURRENT_REQ_ID.remove();
        INVOKE_STAMP.remove();
    }

    /**
     * Was the request that created this owner entry still running when we read it, and was it on
     * the SAME page context as this request at the time? "Same page context" is the causal link:
     * it means the foreign object's creator and this request were co-using one shared page (a
     * WireBox singleton's), which is where per-invocation construction state can cross.
     */
    private static void classifyCrossing( String prefix, Object[] owner ) {
        Object builtInReq = owner[1];
        boolean creatorLive = ( builtInReq instanceof Long ) && LIVE_REQS.containsKey( builtInReq );
        count( prefix + ( creatorLive ? ".creatorStillRunning" : ".creatorAlreadyFinished" ) );
        if ( creatorLive ) {
            Integer mine = REQ_PAGECTX.get( CURRENT_REQ_ID.get() );
            Integer theirs = REQ_PAGECTX.get( (Long) builtInReq );
            if ( mine != null && mine.equals( theirs ) ) {
                count( prefix + ".sameLivePageContext" );
            } else {
                count( prefix + ".differentPageContext" );
            }
        }
    }

    // ---- container walk: name the shared object that carries the crossing -------------------
    //
    // The crossing is two concurrent requests sharing one live object. The only reference to a
    // per-request transient from a process-wide singleton is the bug, so walking from a singleton
    // to the foreign object names the field that leaks it. This is expensive, so it runs only on
    // the first few crossings and is hard-bounded on nodes and depth.

    private static final int WALK_MAX_DEPTH = 8;
    private static final int WALK_MAX_NODES = 120000;
    private static final int WALK_SAMPLES   = 12;

    /**
     * Find the WireBox Injector singleton from a Quick entity. Every entity holds
     * variables._wirebox, and the Injector is one object shared by every request, which makes it
     * the right root: any path from it to a request's transient scope is the leak.
     */
    private static Object injectorFrom( Object proxy ) {
        Object scope = call( proxy, "getVariableScope" );
        if ( !( scope instanceof Map ) ) return null;
        try {
            for ( Map.Entry<?, ?> e : ( (Map<?, ?>) scope ).entrySet() ) {
                String k = ( e.getKey() == null ) ? "" : e.getKey().toString();
                if ( k.equalsIgnoreCase( "_wirebox" ) ) {
                    return unwrapVariable( e.getValue() );
                }
            }
        } catch ( RuntimeException ignored ) { /* scope changed under us; give up */ }
        return null;
    }

    /**
     * Breadth-first walk from root to the exact object `target` (by identity), returning a short
     * "field/{key}/[i]" path or null if the target was not reached inside the budget. The first
     * edge that leaves a singleton for a request-local object is what a fix has to cut.
     */
    private static String pathTo( Object root, Object target ) {
        if ( root == null || target == null || root == target ) return null;
        java.util.IdentityHashMap<Object, Object> pred = new java.util.IdentityHashMap<Object, Object>();
        java.util.IdentityHashMap<Object, String> edge = new java.util.IdentityHashMap<Object, String>();
        java.util.IdentityHashMap<Object, Integer> depth = new java.util.IdentityHashMap<Object, Integer>();
        ArrayDeque<Object> q = new ArrayDeque<Object>();
        pred.put( root, root );
        depth.put( root, Integer.valueOf( 0 ) );
        q.add( root );
        int nodes = 0;

        while ( !q.isEmpty() ) {
            Object cur = q.pollFirst();
            if ( cur == target ) return buildPath( pred, edge, root, target );
            int d = depth.get( cur ).intValue();
            if ( d >= WALK_MAX_DEPTH ) continue;
            if ( ++nodes > WALK_MAX_NODES ) return null;

            for ( Object[] child : childrenOf( cur ) ) {
                Object c = child[0];
                if ( c == null ) continue;
                if ( c == target ) {
                    pred.put( c, cur );
                    edge.put( c, (String) child[1] );
                    return buildPath( pred, edge, root, target );
                }
                if ( skipWalk( c ) || pred.containsKey( c ) ) continue;
                pred.put( c, cur );
                edge.put( c, (String) child[1] );
                depth.put( c, Integer.valueOf( d + 1 ) );
                q.add( c );
            }
        }
        return null;
    }

    private static String buildPath( java.util.IdentityHashMap<Object, Object> pred,
                                      java.util.IdentityHashMap<Object, String> edge,
                                      Object root, Object target ) {
        java.util.ArrayList<String> parts = new java.util.ArrayList<String>();
        Object cur = target;
        int guard = 0;
        while ( cur != root && guard++ < 64 ) {
            parts.add( edge.get( cur ) + "(" + shortClass( cur ) + ")" );
            cur = pred.get( cur );
            if ( cur == null ) break;
        }
        StringBuilder sb = new StringBuilder();
        sb.append( shortClass( root ) );
        for ( int i = parts.size() - 1; i >= 0; i-- ) sb.append( " -> " ).append( parts.get( i ) );
        return sb.toString();
    }

    /** The children of one node: map values, collection/array elements, or declared fields. */
    private static java.util.List<Object[]> childrenOf( Object o ) {
        java.util.ArrayList<Object[]> out = new java.util.ArrayList<Object[]>();
        try {
            if ( o instanceof Map ) {
                int n = 0;
                for ( Map.Entry<?, ?> e : ( (Map<?, ?>) o ).entrySet() ) {
                    if ( n++ > 2000 ) break;
                    out.add( new Object[]{ unwrapVariable( e.getValue() ),
                        "{" + trimKey( e.getKey() ) + "}" } );
                }
                return out;
            }
            if ( o instanceof Iterable ) {
                int i = 0;
                for ( Object e : (Iterable<?>) o ) {
                    if ( i > 2000 ) break;
                    out.add( new Object[]{ unwrapVariable( e ), "[" + i++ + "]" } );
                }
                return out;
            }
            if ( o.getClass().isArray() && !o.getClass().getComponentType().isPrimitive() ) {
                Object[] a = (Object[]) o;
                for ( int i = 0; i < a.length && i < 2000; i++ ) {
                    out.add( new Object[]{ a[i], "[" + i + "]" } );
                }
                return out;
            }
            for ( Class<?> c = o.getClass(); c != null && c != Object.class; c = c.getSuperclass() ) {
                for ( Field f : c.getDeclaredFields() ) {
                    if ( java.lang.reflect.Modifier.isStatic( f.getModifiers() ) ) continue;
                    if ( f.getType().isPrimitive() ) continue;
                    try {
                        f.setAccessible( true );
                        out.add( new Object[]{ f.get( o ), f.getName() } );
                    } catch ( Exception ignored ) { /* skip inaccessible field */ }
                }
            }
        } catch ( Throwable ignored ) { /* never let the walk break the engine */ }
        return out;
    }

    private static String trimKey( Object k ) {
        String s = str( k );
        return s.length() > 40 ? s.substring( 0, 40 ) : s;
    }

    private static String shortClass( Object o ) {
        if ( o == null ) return "null";
        String n = o.getClass().getName();
        int dot = n.lastIndexOf( '.' );
        return dot >= 0 ? n.substring( dot + 1 ) : n;
    }

    /**
     * Nodes the walk must not enter: JVM plumbing that reaches the whole heap (classloaders,
     * threads, references), and leaves that cannot lead anywhere useful. Skipping these keeps the
     * walk bounded and stops it wandering out of the application object graph.
     */
    private static boolean skipWalk( Object o ) {
        if ( o == null ) return true;
        if ( o instanceof String || o instanceof Number || o instanceof Boolean
            || o instanceof Character || o instanceof Class || o instanceof ClassLoader
            || o instanceof Thread || o instanceof java.lang.ref.Reference
            || o instanceof java.lang.reflect.Member || o.getClass().isEnum() ) {
            return true;
        }
        String n = o.getClass().getName();
        if ( n.startsWith( "coldfusion.runtime.ScopeTrace" ) ) return true;
        if ( n.startsWith( "sun." ) || n.startsWith( "jdk." ) || n.startsWith( "java.security" )
            || n.startsWith( "java.lang.Class" ) || n.startsWith( "java.util.concurrent.atomic" ) ) {
            return true;
        }
        return false;
    }

    /** A CFML built-in scope (APPLICATION, SERVER, ...) from the page context, or null. */
    private static Object builtinScope( Object pageCtx, String name ) {
        if ( pageCtx == null ) return null;
        try {
            Method m = pageCtx.getClass().getMethod( "SymTab_findBuiltinScope", String.class );
            m.setAccessible( true );
            return m.invoke( pageCtx, name );
        } catch ( Throwable t ) { return null; }
    }

    /** The static component cache and base metadata on TemplateProxyFactory, read once. */
    private static Object staticField( String className, String fieldName ) {
        try {
            Class<?> c = Class.forName( className );
            Field f = c.getDeclaredField( fieldName );
            f.setAccessible( true );
            return f.get( null );
        } catch ( Throwable t ) { return null; }
    }

    /**
     * Walk from several process-wide roots to the foreign object and record which root reaches
     * it, by what path. A transient is not supposed to be reachable from ANY of these, so the
     * first root that reaches it names the container that leaks it between concurrent requests.
     *
     * Roots, in order of suspicion:
     *   metadata   — the shared per-class AttributeCollection both concurrent builds write to
     *   compCache  — TemplateProxyFactory's static component cache
     *   appScope   — the application scope, shared by every request
     *   injector   — the WireBox Injector singleton
     */
    private static void nameContainer( String tag, Object entityProxy, Object foreign, Object[] owner ) {
        if ( countShape( "WALK_" + tag ) > WALK_SAMPLES ) return;

        Object page = field( entityProxy, "page" );
        Object pageCtx = ( page == null ) ? null : field( page, "pageContext" );
        Object[][] roots = new Object[][] {
            { "metadata",  call( entityProxy, "getMetadata" ) },
            { "compCache", staticField( "coldfusion.runtime.TemplateProxyFactory", "componentCache" ) },
            { "baseMeta",  staticField( "coldfusion.runtime.TemplateProxyFactory", "baseMetaData" ) },
            { "appScope",  builtinScope( pageCtx, "APPLICATION" ) },
            { "serverScope", builtinScope( pageCtx, "SERVER" ) },
            { "injector",  injectorFrom( entityProxy ) },
        };

        boolean any = false;
        for ( Object[] r : roots ) {
            Object root = r[1];
            if ( root == null ) continue;
            String path = pathTo( root, foreign );
            if ( path == null ) continue;
            any = true;
            count( "container." + tag + ".found." + r[0] );
            writeRaw( line( "CONTAINER_PATH", "tag=" + tag, "root=" + (String) r[0],
                "foreign=" + id( foreign ), "builtBy=" + owner[2], "path=" + path ) );
            break; // the first (most-suspicious) root that reaches it is the answer
        }
        if ( !any ) {
            count( "container." + tag + ".notFoundFromAnyRoot" );
            writeRaw( line( "CONTAINER_WALK", "tag=" + tag, "result=notFoundFromAnyRoot",
                "foreign=" + id( foreign ), "builtBy=" + owner[2] ) );
        }
    }

    private static void stat( int index ) {
        if ( CURRENT_REQ_ID.get() == null ) return;
        STATS.get()[ index ]++;
    }

    /** True when the owner label's request was working on a different entity than this one. */
    private static boolean otherEntity( Object[] owner ) {
        String label = String.valueOf( owner[2] );
        int slash = label.indexOf( '/' );
        String ownerReq = ( slash > 0 ) ? label.substring( 0, slash ) : label;
        return !ownerReq.equals( nz( CURRENT_REQ.get() ) );
    }

    private static String leaf( String s ) {
        if ( s == null ) return "";
        int cut = Math.max( s.lastIndexOf( '.' ),
                  Math.max( s.lastIndexOf( '/' ), s.lastIndexOf( '\\' ) ) );
        return ( cut >= 0 && cut < s.length() - 1 ) ? s.substring( cut + 1 ) : s;
    }

    // ---- reflection helpers ---------------------------------------------------------------
    // All of this is best effort. A diagnostic must never throw into the engine, so every
    // lookup swallows failures and returns a placeholder.

    private static final ConcurrentHashMap<String, Field>   FIELDS  = new ConcurrentHashMap<String, Field>();
    private static final ConcurrentHashMap<String, Method>  METHODS = new ConcurrentHashMap<String, Method>();
    private static final ConcurrentHashMap<String, Boolean> ABSENT  = new ConcurrentHashMap<String, Boolean>();

    private static Object arg( Object[] args, int i ) {
        return ( args != null && args.length > i ) ? args[i] : null;
    }

    private static Object field( Object o, String name ) {
        if ( o == null ) return null;
        String key = o.getClass().getName() + "#" + name;
        if ( ABSENT.containsKey( key ) ) return null;
        Field f = FIELDS.get( key );
        if ( f == null ) {
            for ( Class<?> c = o.getClass(); c != null && c != Object.class; c = c.getSuperclass() ) {
                try {
                    Field cand = c.getDeclaredField( name );
                    cand.setAccessible( true );
                    f = cand;
                    break;
                } catch ( Exception ignored ) { /* keep walking up the chain */ }
            }
            if ( f == null ) { ABSENT.put( key, Boolean.TRUE ); return null; }
            FIELDS.put( key, f );
        }
        try { return f.get( o ); } catch ( Exception e ) { return null; }
    }

    private static Object call( Object o, String name ) {
        if ( o == null ) return null;
        String key = o.getClass().getName() + "." + name;
        if ( ABSENT.containsKey( key ) ) return null;
        Method m = METHODS.get( key );
        if ( m == null ) {
            for ( Class<?> c = o.getClass(); c != null && c != Object.class; c = c.getSuperclass() ) {
                try {
                    Method cand = c.getDeclaredMethod( name );
                    cand.setAccessible( true );
                    m = cand;
                    break;
                } catch ( Exception ignored ) { /* keep walking up the chain */ }
            }
            if ( m == null ) { ABSENT.put( key, Boolean.TRUE ); return null; }
            METHODS.put( key, m );
        }
        try { return m.invoke( o ); } catch ( Exception e ) { return null; }
    }

    private static final ConcurrentHashMap<Class<?>, Boolean> IS_PROXY = new ConcurrentHashMap<Class<?>, Boolean>();

    /** Walking the class hierarchy on every call is too slow here, so the answer is cached. */
    private static boolean isProxy( Object o ) {
        if ( o == null ) return false;
        Class<?> k = o.getClass();
        Boolean cached = IS_PROXY.get( k );
        if ( cached != null ) return cached.booleanValue();
        boolean found = false;
        for ( Class<?> c = k; c != null; c = c.getSuperclass() ) {
            if ( "coldfusion.runtime.TemplateProxy".equals( c.getName() ) ) { found = true; break; }
        }
        IS_PROXY.put( k, Boolean.valueOf( found ) );
        return found;
    }

    /** The component's full name, so an Alpha/Bravo crossing is obvious on sight. */
    private static String cfcName( Object proxy ) {
        if ( proxy == null ) return "-";
        Object n = field( proxy, "cfcFullyQualifiedName" );
        if ( n != null ) return str( n );
        return proxy.getClass().getName();
    }

    private static String id( Object o ) {
        return ( o == null ) ? "null" : Integer.toHexString( System.identityHashCode( o ) );
    }

    private static String nz( String s ) { return ( s == null || s.length() == 0 ) ? "-" : s; }

    /** Full CFC paths make every line unreadable; the file name is enough to tell them apart. */
    private static String shortPath( Object o ) {
        if ( o == null ) return "-";
        String s = str( o );
        int cut = Math.max( s.lastIndexOf( '/' ), s.lastIndexOf( '\\' ) );
        return ( cut >= 0 && cut < s.length() - 1 ) ? s.substring( cut + 1 ) : s;
    }

    private static String str( Object o ) {
        if ( o == null ) return "-";
        String s;
        try { s = String.valueOf( o ); } catch ( RuntimeException e ) { return "?"; }
        if ( s.length() > 200 ) { s = s.substring( 0, 200 ); }
        return s.replace( '\t', ' ' ).replace( '\n', ' ' ).replace( '\r', ' ' );
    }

    // ---- recording -------------------------------------------------------------------------

    private static long counterValue( String key ) {
        AtomicLong a = COUNTERS.get( key );
        return ( a == null ) ? 0L : a.get();
    }

    private static void count( String key ) { add( key, 1L ); }

    private static void add( String key, long n ) {
        AtomicLong a = COUNTERS.get( key );
        if ( a == null ) {
            COUNTERS.putIfAbsent( key, new AtomicLong() );
            a = COUNTERS.get( key );
        }
        a.addAndGet( n );
    }

    private static String line( String event, String... pairs ) {
        StringBuilder sb = new StringBuilder( 224 );
        sb.append( System.currentTimeMillis() ).append( '\t' )
          .append( System.nanoTime() ).append( '\t' )
          .append( Thread.currentThread().getName() ).append( '\t' )
          .append( event );
        for ( int i = 0; i < pairs.length; i++ ) {
            sb.append( '\t' ).append( pairs[i] );
        }
        return sb.toString();
    }

    /** Hold the event in memory for this thread. Nothing reaches disk unless the request fails. */
    private static void ring( String ev ) {
        ArrayDeque<String> q = RING_BUF.get();
        if ( q.size() >= RING ) q.pollFirst();
        q.addLast( ev );
    }

    private static void dumpRing( String tail ) {
        ArrayDeque<String> q = RING_BUF.get();
        synchronized ( WRITE_LOCK ) {
            for ( String s : q ) writeRawLocked( s );
            writeRawLocked( tail );
        }
        q.clear();
    }

    /** Write the first few examples of each distinct event shape, then leave it to the counters. */
    private static void sample( String shape, String ev ) {
        if ( countShape( shape ) <= SHAPE_SAMPLES ) writeRaw( ev );
    }

    /** How many times this shape has been seen, so callers can skip work after the first few. */
    private static long countShape( String shape ) {
        AtomicLong a = SHAPES.get( shape );
        if ( a == null ) {
            SHAPES.putIfAbsent( shape, new AtomicLong() );
            a = SHAPES.get( shape );
        }
        return a.incrementAndGet();
    }

    private static void writeRaw( String lineText ) {
        synchronized ( WRITE_LOCK ) { writeRawLocked( lineText ); }
    }

    private static void writeRawLocked( String lineText ) {
        if ( writer == null ) return;
        if ( linesWritten.incrementAndGet() > MAX_LINES ) return;
        try {
            writer.write( lineText );
            writer.write( '\n' );
        } catch ( IOException e ) {
            writer = null;
        }
    }

    private static void flush() {
        synchronized ( WRITE_LOCK ) {
            if ( writer == null ) return;
            try { writer.flush(); } catch ( IOException ignored ) { }
        }
    }

    /** Counters go to their own file so a big trace file never hides the totals. */
    public static void dumpCounters() {
        if ( !ON ) return;
        StringBuilder sb = new StringBuilder( 2048 );
        sb.append( "# scope trace counters at " ).append( System.currentTimeMillis() ).append( '\n' );
        sb.append( "linesWritten\t" ).append( linesWritten.get() )
          .append( "\t(cap " ).append( MAX_LINES ).append( ")\n" );
        sb.append( "trackedScopes\t" ).append( SCOPE_OWNER.size() ).append( '\n' );

        // The comparison this whole build exists to make: per request, what do the requests that
        // FAILED do more of than the ones that succeeded? A number that is much larger on the
        // FAIL line is a candidate cause. A number that matches is background noise.
        long ok   = counterValue( "requests.OK" );
        long fail = counterValue( "requests.FAIL" );
        sb.append( "\n# average per request, by outcome  (OK=" ).append( ok )
          .append( " FAIL=" ).append( fail ).append( ")\n" );
        sb.append( "# measure\tperOkRequest\tperFailRequest\tratio\n" );
        for ( int i = 0; i < S_COUNT; i++ ) {
            double a = ( ok   == 0 ) ? 0 : (double) counterValue( "perRequest.OK."   + STAT_NAMES[i] ) / ok;
            double b = ( fail == 0 ) ? 0 : (double) counterValue( "perRequest.FAIL." + STAT_NAMES[i] ) / fail;
            String ratio = ( a == 0 ) ? ( b == 0 ? "-" : "new" ) : String.format( "%.2fx", Double.valueOf( b / a ) );
            sb.append( "AVG\t" ).append( STAT_NAMES[i] ).append( '\t' )
              .append( String.format( "%.1f", Double.valueOf( a ) ) ).append( '\t' )
              .append( String.format( "%.1f", Double.valueOf( b ) ) ).append( '\t' )
              .append( ratio ).append( '\n' );
        }
        sb.append( '\n' );

        TreeMap<String, AtomicLong> sorted = new TreeMap<String, AtomicLong>( COUNTERS );
        for ( Map.Entry<String, AtomicLong> e : sorted.entrySet() ) {
            sb.append( e.getKey() ).append( '\t' ).append( e.getValue().get() ).append( '\n' );
        }
        BufferedWriter w = null;
        try {
            w = new BufferedWriter( new FileWriter( PATH + ".counters", false ) );
            w.write( sb.toString() );
        } catch ( IOException ignored ) {
        } finally {
            if ( w != null ) { try { w.close(); } catch ( IOException ignored ) { } }
        }
    }

    private static void startCounterThread() {
        Thread t = new Thread( new Runnable() {
            public void run() {
                while ( true ) {
                    try { Thread.sleep( 2000L ); } catch ( InterruptedException e ) { return; }
                    dumpCounters();
                    flush();
                }
            }
        }, "cfscope-trace-counters" );
        t.setDaemon( true );
        t.start();
    }

