    /**
     * Bounded walk from `root` that stops at the first node which is a scope/struct owned by a
     * DIFFERENT request that is still running. Returns { foundNode, ownerEntry, pathString } or
     * null. This is the "goal is a predicate" cousin of pathTo.
     */
    private static Object[] findForeignLive( Object root, int maxDepth, int maxNodes ) {
        if ( root == null ) return null;
        Long me = CURRENT_REQ_ID.get();
        if ( me == null ) return null;
        java.util.IdentityHashMap<Object, Object> pred = new java.util.IdentityHashMap<Object, Object>();
        java.util.IdentityHashMap<Object, String> edge = new java.util.IdentityHashMap<Object, String>();
        java.util.IdentityHashMap<Object, Integer> depth = new java.util.IdentityHashMap<Object, Integer>();
        ArrayDeque<Object> q = new ArrayDeque<Object>();
        pred.put( root, root );
        depth.put( root, Integer.valueOf( 0 ) );
        q.add( root );
        int nodes = 0;

        while ( !q.isEmpty() ) {
            Object cur = q.pollFirst();

            // Is this node itself a registered scope/struct owned by another live request?
            Object[] owner = foreignOwnerLive( cur, me );
            if ( owner != null ) return new Object[]{ cur, owner, buildPath( pred, edge, root, cur ) };
            // Or an entity whose variables scope is?
            if ( isProxy( cur ) ) {
                Object sc = call( cur, "getVariableScope" );
                Object[] o2 = foreignOwnerLive( sc, me );
                if ( o2 != null ) return new Object[]{ sc, o2, buildPath( pred, edge, root, cur ) + "/getVariableScope" };
            }

            int d = depth.get( cur ).intValue();
            if ( d >= maxDepth ) continue;
            if ( ++nodes > maxNodes ) return null;
            for ( Object[] child : childrenOf( cur ) ) {
                Object c = child[0];
                if ( c == null || skipWalk( c ) || pred.containsKey( c ) ) continue;
                pred.put( c, cur );
                edge.put( c, (String) child[1] );
                depth.put( c, Integer.valueOf( d + 1 ) );
                q.add( c );
            }
        }
        return null;
    }

    /** foreignOwner, but only returns when the creating request is also still running. */
    private static Object[] foreignOwnerLive( Object scope, Long me ) {
        Object[] o = foreignOwner( scope );
        if ( o == null ) return null;
        Object builtInReq = o[1];
        if ( me.equals( builtInReq ) ) return null;
        return ( builtInReq instanceof Long && LIVE_REQS.containsKey( builtInReq ) ) ? o : null;
    }

