    /**
     * UDFMethod.invoke(FusionContext). args[0] = the context. When the hook runs the original
     * has just returned, so ctx.returnValue holds what the CFML function returned and ctx.args
     * still holds this call's ArgumentCollection (the caller restores them later).
     *
     * Three checks, and their disagreement is the whole point:
     *   - the RETURN value being foreign says a function handed the object out;
     *   - an ARGUMENT being foreign says the object arrived through argument passing;
     *   - the TARGET (ctx.instance) being foreign while the arguments are clean says the value
     *     flow was correct and the engine dispatched the call to the wrong object.
     * Earlier rounds showed getInstance never RETURNS a foreign object, yet the relationship
     * init sees a foreign `arguments.related` — so the answer is in one of the last two.
     */
    public static void udfInvokeReturn( Object self, Object[] args, Object result ) {
        if ( !ON ) return;
        try {
            if ( CURRENT_REQ_ID.get() == null ) return;
            Object ctx = arg( args, 0 );
            if ( ctx == null ) return;

            // Which functions carry the one-way iscfthread latch? Those run on the shared
            // threadLocalScope frame instead of a fresh one, so this list IS the blast radius.
            if ( Boolean.TRUE.equals( field( self, "iscfthread" ) ) ) {
                count( "udf.ISCFTHREAD." + fnLabel( self ) );
            }

            // 1. the return value
            Object returned = field( ctx, "returnValue" );
            if ( isProxy( returned ) ) {
                count( "udfReturn.component" );
                Object[] owner = foreignOwner( call( returned, "getVariableScope" ) );
                if ( owner == null ) {
                    count( "udfReturn.ownObject" );
                } else {
                    count( "udfReturn.FOREIGN" );
                    count( "udfReturn.FOREIGN." + fnLabel( self ) );
                    if ( countShape( "UDF_RETURNED_FOREIGN" ) <= SHAPE_SAMPLES ) {
                        writeStack( "UDF_RETURNED_FOREIGN", owner );
                    }
                }
            }

            // 2. the invocation target
            Object target = field( ctx, "instance" );
            if ( isProxy( target ) ) {
                Object[] owner = foreignOwner( call( target, "getVariableScope" ) );
                if ( owner != null ) {
                    count( "udfTarget.FOREIGN" );
                    count( "udfTarget.FOREIGN." + fnLabel( self ) );
                }
            }

            // 3. the ArgumentCollection itself, then every value in it.
            //
            // The collection OBJECT is tracked in the owner table like a scope. Collections are
            // supposed to be per-call; if the same collection object ever shows up in two
            // requests that are both still running, the engine is sharing live argument state
            // between threads — which would explain a foreign entity appearing in the arguments
            // of a function whose CFML signature takes no components at all.
            Object argCol = field( ctx, "args" );
            if ( argCol instanceof Map ) {
                Object[] colOwner = foreignOwner( argCol );
                if ( colOwner != null ) {
                    count( "CROSSING.argCollection" );
                    count( "CROSSING.argCollection." + fnLabel( self ) );
                    if ( countShape( "ARGCOL_SHARED" ) <= 2 * SHAPE_SAMPLES ) {
                        writeStack( "ARGCOL_SHARED fn=" + fnLabel( self ) + " col=" + id( argCol ), colOwner );
                    }
                } else {
                    rememberOwner( argCol, "ArgCol:" + fnLabel( self ) );
                }

                Map<?, ?> m = (Map<?, ?>) argCol;
                if ( m.size() <= 30 ) {
                    for ( Map.Entry<?, ?> e : m.entrySet() ) {
                        Object val = unwrapVariable( e.getValue() );
                        // one level of nesting, so a component inside a passed struct
                        // (WireBox's initArguments) is visible at every hop it travels
                        if ( val instanceof Map && !isProxy( val ) ) {
                            Map<?, ?> inner = (Map<?, ?>) val;
                            if ( inner.size() <= 30 ) {
                                for ( Map.Entry<?, ?> ie : inner.entrySet() ) {
                                    checkArgValue( self, argCol,
                                        str( e.getKey() ) + "." + str( ie.getKey() ),
                                        unwrapVariable( ie.getValue() ) );
                                }
                            }
                            continue;
                        }
                        checkArgValue( self, argCol, str( e.getKey() ), val );
                    }
                }
            }
        } catch ( Throwable t ) { count( "trace.error" ); }
    }

    private static void checkArgValue( Object udf, Object argCol, String key, Object val ) {
        if ( !isProxy( val ) ) return;
        Object[] owner = foreignOwner( call( val, "getVariableScope" ) );
        if ( owner == null ) return;
        count( "udfArg.FOREIGN" );
        count( "udfArg.FOREIGN." + fnLabel( udf ) + "[" + key + "]" );
        if ( countShape( "UDF_ARG_FOREIGN" ) <= 3 * SHAPE_SAMPLES ) {
            writeStack( "UDF_ARG_FOREIGN fn=" + fnLabel( udf )
                + " key=" + key
                + " valCfc=" + cfcName( val )
                + " col=" + id( argCol )
                + " colSize=" + ( (Map<?, ?>) argCol ).size(), owner );
        }
    }

    /**
     * UDFMethod.invoke(Object instance, String calledName, Object parent, Map namedArgs).
     * args[3] = the caller's raw struct, checked BEFORE (well, unchanged by) the engine's
     * conversion to an ArgumentCollection. Together with the collection-side check this splits
     * the question: dirty struct = the pollution is upstream in CFML-visible struct state;
     * clean struct but dirty collection = the engine's conversion machinery is the polluter.
     */
    public static void udfMapInvoke( Object self, Object[] args, Object result ) {
        if ( !ON ) return;
        try {
            if ( CURRENT_REQ_ID.get() == null ) return;
            Object namedArgs = arg( args, 3 );
            if ( !( namedArgs instanceof Map ) ) return;
            count( "mapInvoke.total" );
            Map<?, ?> m = (Map<?, ?>) namedArgs;
            if ( m.size() > 30 ) return;

            // Did the struct OBJECT itself cross from another in-flight request? That is a very
            // different bug from foreign VALUES copied into this request's own struct, and it
            // decides where the fix goes: reference plumbing vs the copy source.
            Object[] structOwner = foreignOwner( namedArgs );

            // Correlate with the invoke() built-in boundary (frame A) on this same thread. The
            // engine passes the struct straight through with no shared-field read, so comparing
            // the two ends tells us WHERE the crossing happened. This is the decision the hunt
            // turns on: "clean at the BIF, foreign here" is an engine field we can isolate;
            // "foreign at the BIF too" means the crossing is upstream in CFML/WireBox.
            Object[] stamp = INVOKE_STAMP.get();
            if ( stamp != null && stamp[0] == namedArgs ) {
                boolean enteredForeign = ( (Boolean) stamp[1] ).booleanValue();
                if ( structOwner != null && enteredForeign ) {
                    count( "engine.STRUCT_THREADED_CLEAN" );        // foreign before the engine
                } else if ( structOwner != null && !enteredForeign ) {
                    count( "engine.STRUCT_SWAPPED_IN_DISPATCH" );   // clean at BIF, foreign now: engine field
                    if ( countShape( "STRUCT_SWAPPED" ) <= 2 * SHAPE_SAMPLES ) {
                        writeStack( "STRUCT_SWAPPED_IN_DISPATCH fn=" + fnLabel( self )
                            + " struct=" + id( namedArgs ), structOwner );
                    }
                } else if ( structOwner == null && enteredForeign ) {
                    count( "engine.STRUCT_BECAME_OWN" );            // foreign at BIF, own now (unexpected)
                } else {
                    count( "engine.STRUCT_THREADED_OWN" );          // own at both ends: the normal case
                }
            }

            if ( structOwner != null ) {
                count( "mapInvoke.STRUCT_OBJECT_CROSSED" );
                count( "mapInvoke.STRUCT_OBJECT_CROSSED." + fnLabel( self ) );
                classifyCrossing( "mapInvoke.STRUCT_OBJECT_CROSSED", structOwner );
                // args[0] is the object whose method is being invoked — a Quick entity in these
                // frames — so it can reach the Injector; walk from there to the shared struct.
                nameContainer( "struct", arg( args, 0 ), namedArgs, structOwner );
                if ( countShape( "STRUCT_OBJECT_CROSSED" ) <= 2 * SHAPE_SAMPLES ) {
                    writeStack( "STRUCT_OBJECT_CROSSED fn=" + fnLabel( self )
                        + " struct=" + id( namedArgs )
                        + " structClass=" + namedArgs.getClass().getName()
                        + " keys=" + mapKeys( m ), structOwner );
                }
            } else {
                rememberOwner( namedArgs, "invokeStruct:" + fnLabel( self ) );
            }

            for ( Map.Entry<?, ?> e : m.entrySet() ) {
                Object val = unwrapVariable( e.getValue() );
                // Struct-typed argument values (WireBox's nested initArguments) get registered
                // too, so the same struct surfacing later in another request is provable.
                if ( val instanceof Map && !isProxy( val ) ) {
                    Object[] innerOwner = foreignOwner( val );
                    if ( innerOwner != null ) {
                        count( "mapInvoke.INNER_STRUCT_CROSSED" );
                        count( "mapInvoke.INNER_STRUCT_CROSSED." + fnLabel( self ) + "[" + str( e.getKey() ) + "]" );
                        if ( countShape( "INNER_STRUCT_CROSSED" ) <= 2 * SHAPE_SAMPLES ) {
                            writeStack( "INNER_STRUCT_CROSSED fn=" + fnLabel( self )
                                + " key=" + str( e.getKey() )
                                + " struct=" + id( val ), innerOwner );
                        }
                    } else {
                        rememberOwner( val, "argStruct:" + fnLabel( self ) + "[" + str( e.getKey() ) + "]" );
                    }
                    continue;
                }
                if ( !isProxy( val ) ) continue;
                Object[] owner = foreignOwner( call( val, "getVariableScope" ) );
                if ( owner == null ) continue;
                count( "mapInvoke.STRUCT_DIRTY" );
                count( "mapInvoke.STRUCT_DIRTY." + fnLabel( self ) + "[" + str( e.getKey() ) + "]" );
                if ( countShape( "MAP_INVOKE_DIRTY" ) <= 2 * SHAPE_SAMPLES ) {
                    writeStack( "MAP_INVOKE_DIRTY fn=" + fnLabel( self )
                        + " key=" + str( e.getKey() )
                        + " valCfc=" + cfcName( val )
                        + " struct=" + id( namedArgs )
                        + " structClass=" + namedArgs.getClass().getName(), owner );
                }
            }
        } catch ( Throwable t ) { count( "trace.error" ); }
    }

    // ---- frame A: the invoke() built-in function boundary -----------------------------------
    //
    // WireBox builds every entity and relationship with invoke( target, "init", struct ), which
    // compiles to CFPage.invoke(Object,String,Object). That is the first engine frame the struct
    // reaches on the calling thread. Stamping it here, BEFORE the call runs (a pre-hook), lets the
    // deepest frame (udfMapInvoke) tell an upstream crossing from an engine one; and when the
    // struct is already another request's, this records the exact Java+CFML call chain that
    // carried it in — the fact no run has captured, and the one that names the real source.

