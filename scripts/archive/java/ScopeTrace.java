    /**
     * identityHashCode(scope) -> { the scope itself, the id of the request that created it,
     * that request's label }.
     *
     * Keeping the scope object in the entry is what makes this exact. identityHashCode is not
     * unique — two different objects can share one, and a dead object's number can be handed to
     * a new object later — so every lookup checks the stored reference with == before believing
     * the answer. Without that check the table produces false crossings, which is worse than no
     * table at all.
     *
     * Entries are removed when the request that made them finishes, so this holds only the
     * scopes of requests currently in flight: a few thousand entries, and no leak.
     */
    private static final ConcurrentHashMap<Integer, Object[]> SCOPE_OWNER = new ConcurrentHashMap<Integer, Object[]>();

    /** Identities this thread registered for the request it is running, so they can be removed. */
    private static final ThreadLocal<ArrayDeque<Integer>> OWNED = new ThreadLocal<ArrayDeque<Integer>>() {
        protected ArrayDeque<Integer> initialValue() { return new ArrayDeque<Integer>(); }
    };

    /** What the repro app said this thread is doing, from mark("REQ_START ..."). */
    private static final ThreadLocal<String> CURRENT_REQ = new ThreadLocal<String>();

    /**
     * Per-request tallies, rolled up by outcome when the request ends.
     *
     * This is the measurement that matters. Raw crossing counts on their own say nothing: a
     * ColdBox singleton's scope is read by every request by design, so "a scope from another
     * request" happens millions of times per run while only about 4% of requests fail. The
     * question is what is DIFFERENT about the requests that fail. Averaging each tally over
     * failing requests and over succeeding requests answers that directly.
     */
