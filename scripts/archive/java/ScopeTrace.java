    /**
     * args[2] is the named-arg struct for both CFPage.invoke(object,name,arguments) and
     * CfJspPage._invoke(object,name,Map,z,z). Stamp it for frame E, and if it is already a
     * different in-flight request's struct at this boundary, count it, name the container that
     * holds it while it is still alive, and dump the call chain that brought it here.
     */
    private static void bifInvoke0( Object[] args ) {
        if ( CURRENT_REQ_ID.get() == null ) return;
        Object struct = arg( args, 2 );
        if ( !( struct instanceof Map ) ) return;
        Map<?, ?> m = (Map<?, ?>) struct;
        if ( m.size() > 30 ) return;
        count( "bifInvoke.total" );
        Object[] owner = foreignOwner( struct );
        boolean foreign = ( owner != null );
        INVOKE_STAMP.set( new Object[]{ struct, Boolean.valueOf( foreign ) } );
        if ( !foreign ) return;
        count( "bifInvoke.ENTERED_FOREIGN" );
        count( "bifInvoke.ENTERED_FOREIGN.method." + str( arg( args, 1 ) ) );
        classifyCrossing( "bifInvoke.ENTERED_FOREIGN", owner );
        if ( countShape( "BIF_FOREIGN" ) <= 3 * SHAPE_SAMPLES ) {
            writeStack( "BIF_FOREIGN method=" + str( arg( args, 1 ) )
                + " struct=" + id( struct )
                + " structClass=" + struct.getClass().getName()
                + " keys=" + mapKeys( m ), owner );
        }
        nameContainerAtBif( arg( args, 0 ), struct, owner );
    }

    /**
     * Walk to the foreign struct WHILE it is still live. The existing nameContainer runs one frame
     * deeper and only from process-wide roots, and always came back empty because the reference is
     * transient. Here the roots are what a concurrent construction actually shares: the WireBox
     * Injector singleton, the object being invoked, and — last, because it usually reaches the
     * struct trivially as this thread's own local — the calling thread's active page context. The
     * first root that reaches it names the carrier; a hit from the Injector is the leak we want.
     */
    private static void nameContainerAtBif( Object target, Object foreign, Object[] owner ) {
        if ( countShape( "WALK_bif" ) > WALK_SAMPLES ) return;
        Object fusion  = currentFusionContext();
        Object pageCtx = field( fusion, "pageContext" );
        Object[][] roots = new Object[][] {
            { "injector",      injectorFrom( target ) },
            { "targetObject",  target },
            { "activePageCtx", pageCtx },
        };
        for ( Object[] r : roots ) {
            Object root = r[1];
            if ( root == null || root == foreign ) continue;
            String path = pathTo( root, foreign );
            if ( path == null ) continue;
            count( "containerAtBif.found." + r[0] );
            writeRaw( line( "CONTAINER_AT_BIF", "root=" + (String) r[0],
                "foreign=" + id( foreign ), "builtBy=" + str( owner[2] ), "path=" + path ) );
            return;
        }
        count( "containerAtBif.notFoundFromAnyRoot" );
        writeRaw( line( "CONTAINER_AT_BIF", "result=notFoundFromAnyRoot",
            "foreign=" + id( foreign ), "builtBy=" + str( owner[2] ) ) );
    }

    /** The current thread's FusionContext (a ThreadLocal in the engine), for its page context. */
    private static Object currentFusionContext() {
        try {
            Class<?> c = Class.forName( "coldfusion.filter.FusionContext" );
            Method mm = c.getMethod( "getCurrent" );
            return mm.invoke( null );
        } catch ( Throwable t ) { return null; }
    }

    /** "BaseEntity.cfc#hasMany" — enough to find the function without drowning the counters. */
    private static String fnLabel( Object udf ) {
        return shortPath( call( udf, "getPagePath" ) ) + "#" + str( call( udf, "getName" ) );
    }

    /** The first few key names of a map, so a sample line says what kind of struct this is. */
    private static String mapKeys( Map<?, ?> m ) {
        StringBuilder sb = new StringBuilder( 64 );
        int n = 0;
        for ( Object k : m.keySet() ) {
            if ( n++ > 0 ) sb.append( ',' );
            if ( n > 8 ) { sb.append( "..." ); break; }
            sb.append( str( k ) );
        }
        return sb.length() == 0 ? "(empty)" : sb.toString();
    }

    /** ACF scopes sometimes store values wrapped in coldfusion.runtime.Variable. */
    private static Object unwrapVariable( Object v ) {
        if ( v == null ) return null;
        if ( "coldfusion.runtime.Variable".equals( v.getClass().getName() ) ) {
            return call( v, "getValue" );
        }
        return v;
    }

    /**
     * The last live request seen pushing a function frame onto each page context. If two
     * DIFFERENT live requests push onto the SAME NeoPageContext, they are sharing one page's
     * per-invocation scope stacks — which is what happens when both call into the same WireBox
     * singleton, and is a place construction state can cross with nothing persistent holding it.
     */
    private static final java.util.concurrent.ConcurrentHashMap<Integer, Long> PAGECTX_LAST_REQ =
        new java.util.concurrent.ConcurrentHashMap<Integer, Long>();

