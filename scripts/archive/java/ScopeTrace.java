    /** Recent events for this thread, written out only if the request turns out to fail. */
    private static final ThreadLocal<ArrayDeque<String>> RING_BUF = new ThreadLocal<ArrayDeque<String>>() {
        protected ArrayDeque<String> initialValue() { return new ArrayDeque<String>(); }
    };

    /**
     * One slot per thread: the named-arg struct this thread most recently carried into the
     * invoke() built-in function (frame A of the dispatch), together with whether that struct was
     * ALREADY another request's struct at that boundary.
     *
     * The engine passes this struct by reference, unchanged, from the invoke() BIF down to
     * UDFMethod.invoke. So reading the same struct at both ends on the same thread answers the one
     * question the whole hunt turns on: element [0] is the struct, element [1] (Boolean) is
     * "already foreign when it entered the engine". Frame E (udfMapInvoke) checks [0] by identity
     * before trusting [1], so a nested invoke overwriting the slot can only make frame E skip the
     * comparison, never report a wrong answer.
     */
    private static final ThreadLocal<Object[]> INVOKE_STAMP = new ThreadLocal<Object[]>();

    static {
        String p = System.getProperty( "cfscope.trace" );
        if ( p == null || p.length() == 0 ) {
            p = System.getenv( "CFSCOPE_TRACE" );
        }
        PATH = ( p == null || p.length() == 0 ) ? null : p;
        ON   = ( PATH != null );
        MAX_LINES = longProp( "cfscope.trace.maxlines", 400000L );
        RING      = (int) longProp( "cfscope.trace.ring", 300L );

        if ( ON ) {
            try {
                writer = new BufferedWriter( new FileWriter( PATH, true ), 1 << 16 );
            } catch ( IOException e ) {
                writer = null;
            }
            writeRaw( "#start\t" + System.currentTimeMillis() + "\tring=" + RING + "\tmaxLines=" + MAX_LINES );
            startCounterThread();
            Runtime.getRuntime().addShutdownHook( new Thread( new Runnable() {
                public void run() { dumpCounters(); flush(); }
            } ) );
        }
    }

    private static long longProp( String name, long fallback ) {
        try {
            String v = System.getProperty( name );
            if ( v != null && v.trim().length() > 0 ) return Long.parseLong( v.trim() );
        } catch ( RuntimeException ignored ) { /* fall through to the default */ }
        return fallback;
    }

