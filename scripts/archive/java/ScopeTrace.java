    /**
     * UDFMethod.resolveInvocationSuperScope(Object target).
     * args[0] = the invocation target, result = the Scope that will be pushed for `super`.
     *
     * Adobe's v1 fix prefers a per-instance scope here and falls back to the shared
     * UDFMethod.superScope field. The per-instance branch is only reachable when the target is
     * a TemplateProxy, so the first thing worth counting is how often it is not.
     */
    private static void udfResolveSuper0( Object self, Object[] args, Object result ) {
        Object target = arg( args, 0 );
        Object shared = field( self, "superScope" );

        String why;
        if ( target == null )          why = "targetNull";
        else if ( !isProxy( target ) ) why = "targetNotProxy";
        else if ( result == null )     why = "noScopeAnywhere";
        else if ( result == shared )   why = "perInstanceGaveSharedObject";
        else                           why = "perInstanceDistinct";

        count( "udfResolveSuper.total" );
        count( "udfResolveSuper." + why );
        if ( result != null && result == shared ) {
            count( "udfResolveSuper.readSharedObject" );
            stat( S_READ_SHARED );
        }

        // The finding, if there is one: this super scope was created by one request and is being
        // handed to a different request that is running right now.
        Object[] owner = foreignOwner( result );
        if ( owner == null ) {
            // Formatting a line means more reflective reads and a lot of string building, and
            // this runs thousands of times per request. Heavy instrumentation changes the timing
            // of the very race we are trying to catch, so anything that is not a crossing is
            // counted and dropped.
            countShape( "SUPER_READ|" + why );
            return;
        }
        String ownerLabel = String.valueOf( owner[2] );
        String req = nz( CURRENT_REQ.get() );
        boolean other = otherEntity( owner );
        stat( other ? S_CROSS_SUPER_OTHER : S_CROSS_SUPER_SAME );
        count( "CROSSING.superScope.total" );

        // There are millions of these per run and almost all are harmless, so only the first few
        // of each distinct shape get written. The per-request tallies carry the real signal.
        if ( countShape( "SUPER_READ_CROSSED|" + ownerLabel ) <= SHAPE_SAMPLES ) {
            writeRaw( line( "SUPER_READ_CROSSED",
                "udf="        + id( self ),
                "udfPath="    + shortPath( call( self, "getPagePath" ) ),
                "target="     + id( target ),
                "targetCfc="  + cfcName( target ),
                "result="     + id( result ),
                "shared="     + id( shared ),
                "builtFor="   + ownerLabel,
                "builtInReq=" + owner[1],
                "req="        + req,
                "why="        + why ) );
        }
    }

